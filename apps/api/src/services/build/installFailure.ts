/**
 * The failure explained, or null when the failing command wasn't the
 * dependency install (the build itself failed, say).
 */
export function diagnoseInstallFailure(install: InstallInfo, dockerError: string, output: string): string | null {
  if (/corepack install --global|npm install --global npm@/.test(dockerError)) return diagnoseSetupFailure(install, output);
  if (!dockerError.includes(install.command)) return null;
  const text = stripAnsi(output);
  const step = installStepOutput(text, install.command);
  const cause = CAUSES.find((candidate) => candidate.test.test(step));
  const stale = cause === CAUSES[0] && install.staleLockfile ? install.staleLockfile : null;

  const lines = [
    `Dependency installation failed${cause ? `: ${cause.reason}` : ""}.`,
    `Package manager: ${install.manager}${version(install, step)}`,
    `Lockfile: ${install.lockfile ?? "none"}`,
    `Command: ${install.command}`,
  ];
  if (stale) lines.push("Out of date:", ...stale.map((problem) => `  - ${problem}`));
  if (cause) lines.push(`Fix: ${cause.fix(install)}`);
  const excerpt = errorExcerpt(step);
  if (excerpt.length > 0) lines.push(`${install.manager} said:`, ...excerpt.map((line) => `  ${line}`));
  return lines.join("\n");
}

/** Installing the package manager itself failed: the registry couldn't be reached (after retries) or the version doesn't exist. */
function diagnoseSetupFailure(install: InstallInfo, output: string): string {
  const text = stripAnsi(output);
  const spec = `${install.manager}${install.version ? `@${install.version}` : ""}`;
  const missing = /No matching version|Usage Error.*not found|404/i.test(text) && !/Error when performing the request/.test(text);
  const lines = missing
    ? [
        `Couldn't install ${spec}: that version doesn't exist in the npm registry.`,
        `Why: ${install.reason}`,
        `Fix: set "packageManager" in package.json to a published version (e.g. "${install.manager}@<version>").`,
      ]
    : [
        `Couldn't download ${spec} from the npm registry (registry.npmjs.org): the build had no working connection, even after retrying.`,
        "This is a network problem on this server, not in your code.",
        "Fix: check this server's internet connection, DNS and proxy (Docker Desktop: Settings → Resources → Proxies), then redeploy.",
      ];
  const detail = text
    .split("\n")
    .map((line) => line.trim())
    .filter((line) => /Internal Error|Error when performing|ECONN|ETIMEDOUT|ENOTFOUND|EAI_AGAIN|couldn't download|fetch failed/i.test(line))
    .slice(-4);
  if (detail.length > 0) lines.push("Details:", ...detail.map((line) => `  ${line.length > 300 ? `${line.slice(0, 300)}…` : line}`));
  return lines.join("\n");
}

/** The version that actually ran, from corepack's or the tool's own output; else the one detection chose. */
function version(install: InstallInfo, output: string): string {
  const ran =
    new RegExp(`Using ${install.manager} (${VERSION})`).exec(output)?.[1] ??
    new RegExp(`Installing ${install.manager}@(${VERSION})`).exec(output)?.[1] ??
    new RegExp(`using ${install.manager} v(${VERSION})`).exec(output)?.[1] ??
    null;
  if (ran) return ` ${ran} (${install.reason})`;
  return install.version ? ` ${install.version} (${install.reason})` : ` (${install.reason})`;
}

/** Output from the install's RUN step to the end (the step header names its command); the whole tail if the header is gone. */
function installStepOutput(text: string, command: string): string {
  const lines = text.split("\n");
  for (let index = lines.length - 1; index >= 0; index -= 1) {
    const line = lines[index]!;
    if (/^(?:Step \d+\/\d+ : )?RUN /.test(line) && line.includes(command)) return lines.slice(index).join("\n");
  }
  return text;
}

/** The lines that say what went wrong: from the first error line, else the last lines. */
function errorExcerpt(step: string): string[] {
  const lines = step
    .split("\n")
    .map((line) => line.trimEnd())
    .filter((line) => line.trim() !== "" && !/^\s*--->|^Step \d+\/\d+ :|Removed intermediate container|^\s*RUN |returned a non-zero code/.test(line));
  const first = lines.findIndex((line) => /ERR_PNPM_|npm (?:ERR!|error)|^error\b|\bYN\d{4}\b.*(?:error|✘)|^\s*Error:|error:/i.test(line));
  const start = first === -1 ? Math.max(0, lines.length - EXCERPT_LINES) : first;
  return lines.slice(start, start + EXCERPT_LINES).map((line) => (line.length > 300 ? `${line.slice(0, 300)}…` : line));
}

function stripAnsi(text: string): string {
  // eslint-disable-next-line no-control-regex
  return text.replace(/\u001b\[[0-9;]*[A-Za-z]/g, "");
}
