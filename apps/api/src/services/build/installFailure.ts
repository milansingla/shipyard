import type { InstallInfo } from "../detection/types.js";

/**
 * Turns "The command '/bin/sh -c pnpm install --frozen-lockfile' returned a
 * non-zero code: 1" into what actually went wrong, using the install's own
 * output. Never retries or relaxes the install: it only explains it.
 */

/** Output kept from the build for the diagnosis (the install fails early; its output is near the end). */
export const INSTALL_OUTPUT_TAIL_BYTES = 64 * 1024;
const EXCERPT_LINES = 25;
const VERSION = String.raw`\d+(?:\.\d+){0,2}(?:-[\w]+(?:\.[\w]+)*)?`;

interface Cause {
  /** Matches the install's output. */
  test: RegExp;
  reason: string;
  fix: (install: InstallInfo) => string;
}

